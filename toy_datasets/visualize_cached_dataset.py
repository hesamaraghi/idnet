def flow_to_color(flow_x, flow_y, max_magnitude=None):
    """
    Convert optical flow to RGB color visualization.
    Uses HSV colorwheel: hue = direction, saturation = magnitude.
    
    Args:
        flow_x: X component of flow [H, W]
        flow_y: Y component of flow [H, W]
        max_magnitude: Maximum magnitude for normalization (auto if None)
    
    Returns:
        RGB image [H, W, 3] in range [0, 1]
    """
    # Compute magnitude and angle
    magnitude = np.sqrt(flow_x**2 + flow_y**2)
    angle = np.arctan2(flow_y, flow_x)
    
    # Normalize magnitude
    if max_magnitude is None:
        max_magnitude = np.percentile(magnitude[magnitude > 0], 99) if magnitude.max() > 0 else 1.0
    
    magnitude_norm = np.clip(magnitude / max_magnitude, 0, 1)
    
    # Convert angle to hue [0, 1]
    hue = (angle + np.pi) / (2 * np.pi)
    
    # Create HSV image
    hsv = np.stack([hue, magnitude_norm, np.ones_like(magnitude)], axis=-1)
    
    # Convert to RGB
    rgb = colors.hsv_to_rgb(hsv)
    
    return rgb


def create_flow_colorwheel_legend(size=256):
    """Create a colorwheel legend for flow visualization."""
    y, x = np.mgrid[-1:1:size*1j, -1:1:size*1j]
    angle = np.arctan2(y, x)
    magnitude = np.sqrt(x**2 + y**2)
    
    # Mask circle
    mask = magnitude <= 1.0
    
    hue = (angle + np.pi) / (2 * np.pi)
    hsv = np.stack([hue, magnitude, np.ones_like(magnitude)], axis=-1)
    
    rgb = colors.hsv_to_rgb(hsv)
    rgb[~mask] = 1.0  # White background
    
    return rgb


def downsample_events(events, max_events=100000, method='uniform'):
    """
    Downsample events for visualization.
    
    Args:
        events: Structured numpy array
        max_events: Maximum number of events to keep
        method: 'uniform' (temporal uniform) or 'random'
    
    Returns:
        Downsampled events array
    """
    if len(events) <= max_events:
        return events
    
    print(f"   Downsampling {len(events):,} → {max_events:,} events ({method})")
    
    if method == 'uniform':
        # Temporal uniform sampling
        indices = np.linspace(0, len(events)-1, max_events, dtype=int)
    else:  # random
        indices = np.random.choice(len(events), max_events, replace=False)
        indices = np.sort(indices)
    
    return events[indices]


def event_frame_binning(events, num_bins, image_size, two_channels=True):
    """
    Simple event frame binning for visualization.
    
    Args:
        events: Structured numpy array with fields 'x', 'y', 't', 'p'
        num_bins: Number of temporal bins
        image_size: Tuple (height, width)
        two_channels: If True, separate pos/neg channels. If False, single channel.
    
    Returns:
        frames: numpy array of shape [num_bins, channels, height, width]
    """
    height, width = image_size
    
    # Normalize timestamps to [0, num_bins]
    t_min, t_max = events['t'].min(), events['t'].max()
    if t_max == t_min:
        t_normalized = np.zeros_like(events['t'])
    else:
        t_normalized = (events['t'] - t_min) / (t_max - t_min) * (num_bins - 1e-6)
    
    bin_indices = t_normalized.astype(np.int32)
    bin_indices = np.clip(bin_indices, 0, num_bins - 1)
    
    if two_channels:
        frames = np.zeros((num_bins, 2, height, width), dtype=np.float32)
        # Channel 0: positive events, Channel 1: negative events
        for i in range(len(events)):
            x, y, p, bin_idx = events['x'][i], events['y'][i], events['p'][i], bin_indices[i]
            if 0 <= x < width and 0 <= y < height:
                if p == 1:
                    frames[bin_idx, 0, int(y), int(x)] += 1
                else:
                    frames[bin_idx, 1, int(y), int(x)] += 1
    else:
        frames = np.zeros((num_bins, 1, height, width), dtype=np.float32)
        # Single channel: +1 for positive, -1 for negative
        for i in range(len(events)):
            x, y, p, bin_idx = events['x'][i], events['y'][i], events['p'][i], bin_indices[i]
            if 0 <= x < width and 0 <= y < height:
                val = 1 if p == 1 else -1
                frames[bin_idx, 0, int(y), int(x)] += val
    
    return frames


def list_cached_datasets(cache_dir="dataset_cache"):
    """List all cached datasets with their hashes and config info."""
    cache_path = Path(cache_dir)
    if not cache_path.exists():
        print(f"❌ Cache directory not found: {cache_dir}")
        return []
    
    data_files = sorted(cache_path.glob("*_data.pt"))
    
    if not data_files:
        print(f"❌ No cached datasets found in {cache_dir}")
        return []
    
    print(f"\n📦 Found {len(data_files)} cached dataset(s):\n")
    datasets = []
    for i, f in enumerate(data_files):
        hash_prefix = f.stem.replace("_data", "")
        
        # Check for config file
        config_path = cache_path / f"{hash_prefix}_config.yaml"
        has_config = config_path.exists()
        config = None
        
        if has_config:
            try:
                config = OmegaConf.load(config_path)
            except Exception as e:
                print(f"⚠️  Warning: Could not load config {config_path.name}: {e}")
                has_config = False
        
        # Try to load and get basic info
        try:
            data = torch.load(f, weights_only=False)
            num_events = data.pos.size(0)
            time_range = data.pos[:, 2].max() - data.pos[:, 2].min()
            spatial_extent = (data.pos[:, 0].max() - data.pos[:, 0].min(),
                            data.pos[:, 1].max() - data.pos[:, 1].min())
            
            print(f"  [{i}] Hash: {hash_prefix[:16]}...")
            print(f"      File: {f.name}")
            print(f"      Events: {num_events:,}")
            print(f"      Time range: {time_range:.2f}")
            print(f"      Spatial extent: {spatial_extent[0]:.1f} × {spatial_extent[1]:.1f}")
            
            # Display config info if available
            if has_config and config is not None:
                print(f"      Config: ✓ {config_path.name}")
                
                # Show key config parameters
                shape = config.get('shape class', config.get('shape_class', 'unknown'))
                movement = config.get('movement_type', 'unknown')
                method = config.get('event_generation_method', 'unknown')
                
                print(f"         Shape: {shape}, Movement: {movement}, Method: {method}")
                
                # Show texture info if present
                if config.get('use_random_dtd_texture'):
                    dtd_mode = config.get('dtd_texture_mode', 'both')
                    print(f"         DTD Textures: {dtd_mode}")
                    if config.get('fg_image_path'):
                        fg_texture = Path(config.fg_image_path).name
                        print(f"            FG: {fg_texture}")
                    if config.get('bg_image_path'):
                        bg_texture = Path(config.bg_image_path).name
                        print(f"            BG: {bg_texture}")
                
                # Show temporal filter if present
                temporal_filter = config.get('v2e_temporal_filter_percent')
                if temporal_filter is not None:
                    print(f"         Temporal filter: {temporal_filter}%")
            else:
                print(f"      Config: ✗ (not found)")
            
            print()
            
            datasets.append({
                'index': i,
                'hash': hash_prefix,
                'path': f,
                'config_path': config_path if has_config else None,
                'config': config,
                'num_events': num_events,
                'time_range': time_range,
                'spatial_extent': spatial_extent
            })
        except Exception as e:
            print(f"  [{i}] Hash: {hash_prefix[:16]}... (⚠️  Error loading: {e})")
            print()
    
    return datasets


def visualize_dataset(dataset_path, output_dir="visualizations", 
                      num_bins=100, img_size=(256, 256), 
                      time_window=None, save_animation=True,
                      show_plot=False,
                      generator_config=None, auto_config=True,
                      event_animation_fps=20, event_accumulation_ms=20.0,
                      generate_scatter=False, generate_flow_viz=False):
    """
    Visualize a cached dataset.
    
    Args:
        dataset_path: Path to the cached .pt file
        output_dir: Directory to save visualization outputs
        num_bins: Number of time bins for frame-based visualization (default: 100)
        img_size: Image dimensions (H, W)
        time_window: Tuple (start_time, end_time) to visualize subset, or None for all
        save_animation: Whether to save animation as .gif/.mp4
        show_plot: Whether to display plots interactively
        generator_config: Config dict/OmegaConf for DatasetGenerator (overrides auto-detected config)
        auto_config: If True, automatically load config file if it exists next to dataset
        event_animation_fps: FPS for event animation (default: 20)
        event_accumulation_ms: Event accumulation window in ms (default: 20.0)
        generate_scatter: If True, generate scatter plot visualization (default: False)
        generate_flow_viz: If True, generate optical flow visualizations (default: False)
    """
    
    print(f"\n🎬 Visualizing dataset: {dataset_path.name}")
    
    # Auto-detect config file if enabled and not provided
    if auto_config and generator_config is None:
        dataset_hash = dataset_path.stem.replace("_data", "")
        config_path = dataset_path.parent / f"{dataset_hash}_config.yaml"
        
        if config_path.exists():
            try:
                generator_config = OmegaConf.load(config_path)
                print(f"   ✓ Auto-loaded config: {config_path.name}")
                
                # Extract image size from config if available
                if 'image_size' in generator_config:
                    config_img_size = generator_config.image_size
                    if isinstance(config_img_size, (list, tuple)) and len(config_img_size) == 2:
                        img_size = tuple(config_img_size)
                        print(f"   ✓ Using image size from config: {img_size}")
                
            except Exception as e:
                print(f"   ⚠️  Could not load config {config_path.name}: {e}")
        else:
            print(f"   ℹ️  No config file found (looked for {config_path.name})")
    
    print(f"   Loading data...")
    
    # Load data
    data = torch.load(dataset_path, weights_only=False)
    
    # Convert to numpy format for visualization
    data_array = pyg2numpy_event_convertor(data)
    
    # Get time range
    t_min, t_max = data_array['t'].min(), data_array['t'].max()
    print(f"   Events: {len(data_array):,}")
    print(f"   Time range: [{t_min:.2f}, {t_max:.2f}]")
    print(f"   Polarity dist: {(data_array['p'] == 1).sum():,} pos, {(data_array['p'] == 0).sum():,} neg")
    
    # Filter time window if specified
    if time_window is not None:
        t_start, t_end = time_window
        mask = (data_array['t'] >= t_start) & (data_array['t'] <= t_end)
        data_array = data_array[mask]
        print(f"   Filtered to time window [{t_start:.2f}, {t_end:.2f}]: {len(data_array):,} events")
    
    # Generate hash-based filename
    dataset_hash = dataset_path.stem.replace("_data", "")
    base_name = f"{dataset_hash[:12]}"
    
    # Create output directory with hash-specific subdirectory
    output_path = Path(output_dir) / base_name
    output_path.mkdir(parents=True, exist_ok=True)
    
    # -------------------------
    # 1. Event scatter plot
    # -------------------------
    if generate_scatter:
        print(f"   Creating scatter plot...")
        fig, axes = plt.subplots(2, 2, figsize=(14, 12))
        
        # Spatial distribution colored by polarity
        ax = axes[0, 0]
        pos_mask = data_array['p'] == 1
        neg_mask = data_array['p'] == 0
        ax.scatter(data_array['x'][pos_mask], data_array['y'][pos_mask], 
                  c='red', s=0.1, alpha=0.3, label='Positive')
        ax.scatter(data_array['x'][neg_mask], data_array['y'][neg_mask], 
                  c='blue', s=0.1, alpha=0.3, label='Negative')
        ax.set_xlabel('X position')
        ax.set_ylabel('Y position')
        ax.set_title('Spatial Distribution (colored by polarity)')
        ax.legend()
        ax.grid(True, alpha=0.3)
        ax.set_aspect('equal')
        
        # Temporal histogram
        ax = axes[0, 1]
        ax.hist(data_array['t'], bins=100, alpha=0.7, color='green', edgecolor='black')
        ax.set_xlabel('Time')
        ax.set_ylabel('Event count')
        ax.set_title('Event Distribution Over Time')
        ax.grid(True, alpha=0.3)
        
        # X-T plot
        ax = axes[1, 0]
        ax.scatter(data_array['t'], data_array['x'], c=data_array['p'], 
                  cmap='RdBu_r', s=0.1, alpha=0.3)
        ax.set_xlabel('Time')
        ax.set_ylabel('X position')
        ax.set_title('X-T Plot (colored by polarity)')
        ax.grid(True, alpha=0.3)
        
        # Y-T plot
        ax = axes[1, 1]
        ax.scatter(data_array['t'], data_array['y'], c=data_array['p'], 
                  cmap='RdBu_r', s=0.1, alpha=0.3)
        ax.set_xlabel('Time')
        ax.set_ylabel('Y position')
        ax.set_title('Y-T Plot (colored by polarity)')
        ax.grid(True, alpha=0.3)
        
        plt.tight_layout()
        scatter_path = output_path / f"{base_name}_scatter.png"
        plt.savefig(scatter_path, dpi=150, bbox_inches='tight')
        print(f"   ✅ Saved scatter plot: {scatter_path}")
        if show_plot:
            plt.show()
        else:
            plt.close()
    
    # -------------------------
    # 2. Event frames animation
    # -------------------------
    
    if save_animation:
        print(f"   Creating high-quality event animation with {num_bins} frames...")
        
        if generator_config is not None:
            animation_dir = output_path / "generator_animations"
            animation_dir.mkdir(parents=True, exist_ok=True)
            event_animation_path = animation_dir / f"{base_name}_events_hq.gif"
            
            try:
                # Import the event animation function
                sys.path.insert(0, str(Path(__file__).parent))
                from create_dataset_generic import create_event_animation
                
                # Use config values or passed parameters
                fps = generator_config.get('event_animation_fps', event_animation_fps)
                accumulation_ms = generator_config.get('event_accumulation_ms', event_accumulation_ms)
                frame_time_us = generator_config.get('frame_time_us', 1000)
                
                print(f"   Event animation params: fps={fps}, accumulation={accumulation_ms}ms, frame_time={frame_time_us}us")
                
                create_event_animation(
                    events=data_array,
                    image_size=img_size,
                    output_path=str(event_animation_path),
                    fps=fps,
                    accumulation_time_ms=accumulation_ms,
                    frame_time_us=frame_time_us,
                )
                
                print(f"   ✅ Saved high-quality event animation: {event_animation_path}")
                
            except Exception as e:
                print(f"   ⚠️  Could not create event animation: {e}")
        else:
            print(f"   ⚠️  No generator config available, skipping animation")
    
    # -------------------------
    # 3. Sample frames
    # -------------------------
    print(f"   Creating sample frames...")
    frames = event_frame_binning(data_array, num_bins, img_size, two_channels=True)
    
    # Select 6 evenly spaced frames
    frame_indices = np.linspace(0, num_bins-1, 6, dtype=int)
    
    fig, axes = plt.subplots(2, 3, figsize=(15, 10))
    axes = axes.flatten()
    
    for idx, frame_idx in enumerate(frame_indices):
        frame = frames[frame_idx]
        # Create RGB image: red for positive, blue for negative
        rgb = np.zeros((3, *frame.shape[1:]))
        rgb[0] = frame[0] > 0  # Red channel for positive
        rgb[2] = frame[1] > 0  # Blue channel for negative
        rgb = np.moveaxis(rgb, 0, 2)  # Move channel to last dim
        
        axes[idx].imshow(rgb)
        axes[idx].set_title(f'Frame {frame_idx}/{num_bins-1}')
        axes[idx].axis('off')
    
    plt.tight_layout()
    frames_path = output_path / f"{base_name}_sample_frames.png"
    plt.savefig(frames_path, dpi=150, bbox_inches='tight')
    print(f"   ✅ Saved sample frames: {frames_path}")
    if show_plot:
        plt.show()
    else:
        plt.close()
    
    # -------------------------
    # 4. Optical Flow Visualization
    # -------------------------
    if generate_flow_viz and 'v' in data.keys():
        print(f"   Creating optical flow visualizations...")
        
        # Get flow vectors
        flow_gt = data.v.numpy()  # [N, 2] array of (vx, vy)
        
        # For large datasets, downsample for quiver plot
        max_arrows = 5000
        if len(data_array) > max_arrows:
            sample_indices = np.linspace(0, len(data_array)-1, max_arrows, dtype=int)
            events_sample = data_array[sample_indices]
            flow_sample = flow_gt[sample_indices]
        else:
            events_sample = data_array
            flow_sample = flow_gt
        
        # Create comprehensive flow visualization
        fig = plt.figure(figsize=(18, 12))
        gs = fig.add_gridspec(3, 3, hspace=0.3, wspace=0.3)
        
        # 1. Flow magnitude histogram
        ax = fig.add_subplot(gs[0, 0])
        flow_mag = np.sqrt(flow_gt[:, 0]**2 + flow_gt[:, 1]**2)
        ax.hist(flow_mag, bins=50, alpha=0.7, color='purple', edgecolor='black')
        ax.set_xlabel('Flow Magnitude (pixels)')
        ax.set_ylabel('Count')
        ax.set_title(f'Flow Magnitude Distribution\nMean: {flow_mag.mean():.2f}, Max: {flow_mag.max():.2f}')
        ax.grid(True, alpha=0.3)
        
        # 2. Flow direction histogram (polar)
        ax = fig.add_subplot(gs[0, 1], projection='polar')
        flow_angle = np.arctan2(flow_gt[:, 1], flow_gt[:, 0])
        ax.hist(flow_angle, bins=36, alpha=0.7, color='orange')
        ax.set_title('Flow Direction Distribution')
        
        # 3. Flow X vs Y scatter
        ax = fig.add_subplot(gs[0, 2])
        h = ax.hist2d(flow_gt[:, 0], flow_gt[:, 1], bins=50, cmap='viridis', cmin=1)
        plt.colorbar(h[3], ax=ax, label='Count')
        ax.set_xlabel('Flow X (pixels)')
        ax.set_ylabel('Flow Y (pixels)')
        ax.set_title('Flow Vector Distribution')
        ax.grid(True, alpha=0.3)
        ax.set_aspect('equal')
        
        # 4. Quiver plot (arrows) - spatial overview
        ax = fig.add_subplot(gs[1, :])
        # Further downsample for cleaner quiver plot
        stride = max(1, len(events_sample) // 2000)
        x_q = events_sample['x'][::stride]
        y_q = events_sample['y'][::stride]
        vx_q = flow_sample[::stride, 0]
        vy_q = flow_sample[::stride, 1]
        
        q = ax.quiver(x_q, y_q, vx_q, vy_q, flow_mag[sample_indices][::stride],
                     cmap='jet', alpha=0.6, scale=50, width=0.003)
        plt.colorbar(q, ax=ax, label='Flow Magnitude')
        ax.set_xlabel('X position')
        ax.set_ylabel('Y position')
        ax.set_title(f'Optical Flow Field (showing {len(x_q):,} arrows)')
        ax.set_aspect('equal')
        ax.grid(True, alpha=0.3)
        ax.invert_yaxis()
        
        # 5. Flow colorwheel legend
        ax = fig.add_subplot(gs[2, 0])
        colorwheel = create_flow_colorwheel_legend(256)
        ax.imshow(colorwheel)
        ax.set_title('Flow Color Legend\n(Hue=Direction, Brightness=Magnitude)')
        ax.axis('off')
        
        # 6. Flow as color on spatial map
        ax = fig.add_subplot(gs[2, 1])
        # Create dense flow image
        flow_img = np.ones((img_size[0], img_size[1], 3))  # white background
        
        # Sample more points for dense visualization
        sample_dense = min(50000, len(data_array))
        if len(data_array) > sample_dense:
            dense_indices = np.random.choice(len(data_array), sample_dense, replace=False)
            events_dense = data_array[dense_indices]
            flow_dense = flow_gt[dense_indices]
        else:
            events_dense = data_array
            flow_dense = flow_gt
        
        # Compute flow colors
        flow_colors = flow_to_color(flow_dense[:, 0], flow_dense[:, 1])
        
        # Plot as scatter with flow colors
        for i in range(len(events_dense)):
            x, y = int(events_dense['x'][i]), int(events_dense['y'][i])
            if 0 <= x < img_size[1] and 0 <= y < img_size[0]:
                flow_img[y, x] = flow_colors[i]
        
        ax.imshow(flow_img)
        ax.set_title(f'Flow Colormap on Events\n({sample_dense:,} events)')
        ax.axis('off')
        
        # 7. Flow magnitude heatmap
        ax = fig.add_subplot(gs[2, 2])
        mag_img = np.zeros(img_size)
        count_img = np.zeros(img_size)
        
        for i in range(len(events_dense)):
            x, y = int(events_dense['x'][i]), int(events_dense['y'][i])
            if 0 <= x < img_size[1] and 0 <= y < img_size[0]:
                mag = np.sqrt(flow_dense[i, 0]**2 + flow_dense[i, 1]**2)
                mag_img[y, x] += mag
                count_img[y, x] += 1
        
        # Average magnitude per pixel
        mask = count_img > 0
        mag_img[mask] /= count_img[mask]
        
        im = ax.imshow(mag_img, cmap='hot', vmin=0, vmax=np.percentile(flow_mag, 95))
        plt.colorbar(im, ax=ax, label='Avg Flow Magnitude')
        ax.set_title('Flow Magnitude Heatmap')
        ax.axis('off')
        
        plt.suptitle(f'Optical Flow Analysis - {len(data_array):,} events', 
                    fontsize=14, fontweight='bold')
        
        flow_path = output_path / f"{base_name}_optical_flow.png"
        plt.savefig(flow_path, dpi=150, bbox_inches='tight')
        print(f"   ✅ Saved optical flow visualization: {flow_path}")
        
        if show_plot:
            plt.show()
        else:
            plt.close()
        
        # Save flow statistics to text file
        stats_path = output_path / f"{base_name}_flow_stats.txt"
        with open(stats_path, 'w') as f:
            f.write("=" * 60 + "\n")
            f.write("OPTICAL FLOW STATISTICS\n")
            f.write("=" * 60 + "\n\n")
            f.write(f"Total events: {len(data_array):,}\n")
            f.write(f"Time range: [{data_array['t'].min():.2f}, {data_array['t'].max():.2f}]\n\n")
            
            f.write("Flow Magnitude:\n")
            f.write(f"  Mean: {flow_mag.mean():.4f} pixels\n")
            f.write(f"  Std:  {flow_mag.std():.4f} pixels\n")
            f.write(f"  Min:  {flow_mag.min():.4f} pixels\n")
            f.write(f"  Max:  {flow_mag.max():.4f} pixels\n")
            f.write(f"  Median: {np.median(flow_mag):.4f} pixels\n")
            f.write(f"  P95:  {np.percentile(flow_mag, 95):.4f} pixels\n")
            f.write(f"  P99:  {np.percentile(flow_mag, 99):.4f} pixels\n\n")
            
            f.write("Flow X Component:\n")
            f.write(f"  Mean: {flow_gt[:, 0].mean():.4f} pixels\n")
            f.write(f"  Std:  {flow_gt[:, 0].std():.4f} pixels\n")
            f.write(f"  Range: [{flow_gt[:, 0].min():.4f}, {flow_gt[:, 0].max():.4f}]\n\n")
            
            f.write("Flow Y Component:\n")
            f.write(f"  Mean: {flow_gt[:, 1].mean():.4f} pixels\n")
            f.write(f"  Std:  {flow_gt[:, 1].std():.4f} pixels\n")
            f.write(f"  Range: [{flow_gt[:, 1].min():.4f}, {flow_gt[:, 1].max():.4f}]\n\n")
            
            # Dominant direction
            mean_angle = np.arctan2(flow_gt[:, 1].mean(), flow_gt[:, 0].mean())
            mean_angle_deg = np.degrees(mean_angle)
            f.write(f"Mean flow direction: {mean_angle_deg:.2f}° (0°=right, 90°=down)\n")
            
        print(f"   ✅ Saved flow statistics: {stats_path}")
        
        # -------------------------
        # 5. Temporal Slices with Flow Arrows
        # -------------------------
        print(f"   Creating temporal slice visualizations...")
        
        # Select 6 time windows throughout the sequence
        t_min, t_max = data_array['t'].min(), data_array['t'].max()
        time_duration = t_max - t_min
        slice_duration = time_duration / 20  # Each slice is 5% of total duration
        
        # Select 6 evenly spaced time points
        time_points = np.linspace(t_min + slice_duration, t_max - slice_duration, 6)
        
        fig, axes = plt.subplots(2, 3, figsize=(18, 12))
        axes = axes.flatten()
        
        # Determine global flow scale for consistent arrow sizes
        flow_scale = np.percentile(flow_mag, 95) * 5  # Scale up for visibility
        
        for idx, t_center in enumerate(time_points):
            ax = axes[idx]
            
            # Get events in this time window
            t_start = t_center - slice_duration / 2
            t_end = t_center + slice_duration / 2
            mask = (data_array['t'] >= t_start) & (data_array['t'] <= t_end)
            
            events_slice = data_array[mask]
            flow_slice = flow_gt[mask]
            
            n_events = len(events_slice)
            
            if n_events == 0:
                ax.text(0.5, 0.5, 'No events in slice', 
                       ha='center', va='center', transform=ax.transAxes)
                ax.set_title(f'Time: [{t_start:.1f}, {t_end:.1f}]')
                continue
            
            # Downsample for visualization if needed
            max_points = 3000
            if n_events > max_points:
                sample_idx = np.random.choice(n_events, max_points, replace=False)
                events_slice = events_slice[sample_idx]
                flow_slice = flow_slice[sample_idx]
                n_events = max_points
            
            # Separate by polarity
            pos_mask = events_slice['p'] == 1
            neg_mask = events_slice['p'] == 0
            
            # Plot events as scatter
            if pos_mask.any():
                ax.scatter(events_slice['x'][pos_mask], events_slice['y'][pos_mask],
                          c='red', s=3, alpha=0.4, label='Pos events')
            if neg_mask.any():
                ax.scatter(events_slice['x'][neg_mask], events_slice['y'][neg_mask],
                          c='blue', s=3, alpha=0.4, label='Neg events')
            
            # Plot flow arrows (downsample further for arrows)
            max_arrows = 500
            if n_events > max_arrows:
                arrow_stride = n_events // max_arrows
            else:
                arrow_stride = 1
            
            x_arrows = events_slice['x'][::arrow_stride]
            y_arrows = events_slice['y'][::arrow_stride]
            u_arrows = flow_slice[::arrow_stride, 0]
            v_arrows = flow_slice[::arrow_stride, 1]
            
            # Compute magnitude for coloring
            mag_arrows = np.sqrt(u_arrows**2 + v_arrows**2)
            
            # Plot arrows
